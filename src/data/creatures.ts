export function getTodaysMissions() {
  const today = new Date().toDateString();
  const seed = today.split("").reduce((a, c) => a + c.charCodeAt(0), 0);
  const indices = [(seed % 7), ((seed + 2) % 7), ((seed + 4) % 7)];
  return indices.map(i => DAILY_MISSIONS[i]);
}
