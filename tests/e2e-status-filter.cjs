const { chromium } = require('playwright');
(async () => { const b = await chromium.launch(); const p = await b.newPage();
  await p.goto('http://localhost:5199/auth'); await p.click('text=Create account');
  await p.fill('#n','Tester'); await p.fill('#e','t3@example.com'); await p.fill('#p','Password123!'); await p.fill('#y','1990'); await p.check('input[type=checkbox]');
  await p.click('button:has-text("Create account")'); await p.waitForTimeout(2500); console.log(p.url());
  await p.goto('http://localhost:5199/recipe/r2'); await p.waitForSelector('select[aria-label="Cooking status"]');
  await p.click('button[aria-label="Save recipe"]'); await p.selectOption('select[aria-label="Cooking status"]','planned');
  await p.goto('http://localhost:5199/saved'); await p.waitForTimeout(500);
  const all = await p.locator('a[href*="/recipe/"]').count();
  await p.selectOption('select[aria-label="Filter by cooking status"]','planned'); await p.waitForTimeout(300);
  const planned = await p.locator('a[href*="/recipe/r2"]').count();
  await p.selectOption('select[aria-label="Filter by cooking status"]','cooked'); await p.waitForTimeout(300);
  console.log('saved total',all,'planned r4',planned,'cooked-filter links',await p.locator('a[href*="/recipe/"]').count());
  await b.close(); })();
